"""Refresh Rust dependency inventory and bundled license texts from Cargo metadata.
Run after `cargo fetch`; includes build/test and target-specific dependencies.
"""
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
metadata = json.loads(subprocess.check_output(
    ['cargo', 'metadata', '--offline', '--locked', '--format-version', '1'], cwd=ROOT))
packages = sorted((p for p in metadata['packages'] if p['id'] not in metadata['workspace_members']),
                  key=lambda p: (p['name'], p['version']))
rows = ['# Rust dependency inventory', '',
        'Generated by `tools/dependency_inventory.py` from `Cargo.lock` and Cargo metadata.',
        'Includes target-specific, build and test dependencies; not every package ships in every binary.',
        'License expressions are upstream declarations. Full collected texts: [Rust notices](../licenses/RUST-NOTICES.txt).', '',
        '| Package | Version | Declared licence | Source |', '|---|---|---|---|']
notices = ['SecondScrn third-party Rust dependency notices',
           'Generated from the resolved package sources; includes build/test dependencies.', '']
missing = []
for p in packages:
    source = p.get('repository') or f"https://crates.io/crates/{p['name']}/{p['version']}"
    rows.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'See package licence'} | [upstream]({source}) |")
    directory = pathlib.Path(p['manifest_path']).parent
    files = []
    for f in directory.rglob('*'):
        if not f.is_file() or '.git' in f.parts:
            continue
        name = f.name.lower()
        if (name.startswith(('license', 'licence', 'notice', 'copying', 'copyright'))
                and f.suffix.lower() not in ('.rs', '.c', '.h', '.go', '.py')
                and f.stat().st_size < 500_000):
            files.append(f)
    if p.get('license_file'):
        candidate = directory / p['license_file']
        if candidate.is_file() and candidate not in files:
            files.append(candidate)
    notices += ['=' * 78, f"{p['name']} {p['version']}",
                f"Declared licence: {p.get('license')}", f'Source: {source}',
                'Authors: ' + ', '.join(p.get('authors', [])), '']
    if not files:
        missing.append(f"{p['name']} {p['version']}: {p.get('license')}")
    for f in sorted(files):
        notices += [f'--- {f.relative_to(directory).as_posix()} ---',
                    f.read_text(encoding='utf-8', errors='replace'), '']
(ROOT / 'licenses').mkdir(exist_ok=True)
(ROOT / 'docs' / 'rust-dependencies.md').write_text('\n'.join(rows) + '\n', encoding='utf-8')
(ROOT / 'licenses' / 'RUST-NOTICES.txt').write_text('\n'.join(notices) + '\n', encoding='utf-8')
print(f'{len(packages)} packages; {len(missing)} without separate licence files:')
print('\n'.join(missing))
